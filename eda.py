print("Descrição dos Dados de Inspecção (TUXEL):")
print(desc_inspecao)

print("\nDescrição dos Dados de Teste (CTA):")
print(desc_teste)

df_inspecao['Grupo'] = 'Inspeção (TUXEL)'
df_teste['Grupo'] = 'Teste (CTA)'

df_completo = pd.concat([df_inspecao, df_teste], ignore_index=True)

fig, axes = plt.subplots(2, 2, figsize=(12, 10))

variaveis = [
    ('Total_Problemas', 'Total de Problemas'),
    ('Tempo_min', 'Tempo (minutos)'),
    ('Eficacia_pct', 'Eficácia (%)'),
    ('Eficiencia_pct', 'Eficiência (%)'),
]

for ax, (col, titulo) in zip(axes.flatten(), variaveis):
  sns.boxplot(
  x='Grupo',
      y=col,
      data=df_completo,
      ax=ax,
      palette='Set2',
      hue='Grupo',
      legend=False,
      showmeans=True,
  )
  ax.set_title(f'Distribuição de {titulo}', fontsize=12, fontweight='bold')
  ax.set_xlabel('')
  ax.set_ylabel(titulo)

plt.tight_layout()
plt.show()

"""Somente no boxplot da distribuição de tempo do teste (cta) que houve outliers. Esses outliers correspondem aos participantes U3 e U9 que levaram um tempo consideravelmente superior à media do restante do grupo de testes."""

variaveis = ['Total_Problemas', 'Tempo_min', 'Eficacia_pct', 'Eficiencia_pct']

resultados_shapiro = []

for var in variaveis:
  stat_insp, p_insp = stats.shapiro(df_inspecao[var])
  stat_ut, p_ut = stats.shapiro(df_teste[var])

  resultados_shapiro.append({
      'Variável': var,
      'p-valor (Inspeção)': round(p_insp, 4),
      'Normal (Inspeção)?': 'Sim (p >= 0.05)'
      if p_insp >= 0.05
      else 'Não (p < 0.05)',
      'p-valor (Teste UT)': round(p_ut, 4),
      'Normal (Teste UT)?': 'Sim (p >= 0.05)'
      if p_ut >= 0.05
      else 'Não (p < 0.05)',
  })

df_shapiro = pd.DataFrame(resultados_shapiro)
print("Resultados do Teste de Shapiro-Wilk:")
display(df_shapiro)

"""O teste de shapiro wilk foi escolhido para verificar se os dados seguem uma distribuição normal pois ele é ideal para amostras pequenas sendo considerado o teste de normalidade mais poderoso e preciso para amostras com o n < 50. Como nossa amostra possui um n = 9 na inspeção e n = 10 no teste de usabilidade, ele seria o mais viavel para realizar a verificação.

Definição do p-valor:
*   Se p >= 0.05 (distribuição normal) utiliza-se um teste parametrico denomidado Teste t de Student
*   Se p < 0.05 (distribuição não-normal) utiliza-se um teste não parametrico, o Teste de Mann-Whitney

A verificação conclui que todas as amostras seguem uma distribuição normal, ou seja, todas as 4 variaveis serão analisadas com o Teste t de Student.


"""

resultados_ttest = []

for var in variaveis:
  stat, p_val = stats.ttest_ind(
      df_inspecao[var], df_teste[var], equal_var=False
  )

  resultados_ttest.append({
      'Variável': var,
      'Estatística t': round(stat, 3),
      'p-valor': round(p_val, 4),
      'Diferença Significativa?': 'Sim (p < 0.05)'
      if p_val < 0.05
      else 'Não (p >= 0.05)',
  })

df_ttest = pd.DataFrame(resultados_ttest)
print("Resultados do Teste t de Student:")
display(df_ttest)

"""Para interpretar o resultado do Test t é preciso saber que:
*   Se p < 0.05 então existe uma diferença estatistica significativa entre a Inspeção e o Teste de Usabilidade (CTA) assim, rejeitando a hipotese nula H0
*   Se p>= 0.05 então não há diferença significativa entre os dois metodos.

Como todos os p-valores resultaram em valores menores que 0.05, a conclusão é que há uma diferença estatisticamente significativa entre a Inspeção e o Teste de Usabilidade (CTA) em todas as 4 variáveis

Ao analisar os resultados do Teste t de Student e cruzar com as medias calculadas na estatistica descritivas podemos ver que o metodo de inspeção (TUXEL) obteve valores mais altos tanto em Eficacia quanto em Eficiencia.
"""