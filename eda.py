import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from scipy import stats
import warnings

warnings.filterwarnings('ignore')

dados_inspecao = {
    'Participante': ['I1', 'I2', 'I3', 'I4', 'I5', 'I7', 'I8', 'I9', 'I10'],
    'Total_Problemas': [19, 18, 25, 26, 15, 34, 27, 23, 16],
    'Tempo_min': [108, 94, 101, 81, 98, 111, 96, 114, 92],
    'Eficacia_pct': [15.0, 14.2, 19.7, 20.5, 11.8, 26.8, 21.3, 18.1, 12.6],
    'Eficiencia_pct': [10.6, 11.5, 14.9, 19.3, 9.2, 18.4, 16.9, 12.1, 10.4]
}

dados_teste = {
    'Participante': ['U1', 'U2', 'U3', 'U4', 'U5', 'U6', 'U7', 'U8', 'U9', 'U10'],
    'Total_Problemas': [11, 8, 13, 5, 8, 7, 14, 7, 9, 7],
    'Tempo_min': [33, 25, 69, 15, 30, 20, 29, 27, 57, 39],
    'Eficacia_pct': [8.7, 6.3, 10.2, 3.9, 6.3, 5.5, 11.0, 5.5, 7.1, 5.5],
    'Eficiencia_pct': [10.0, 9.6, 5.7, 10.0, 8.0, 10.5, 14.5, 7.8, 4.7, 5.4]
}

print("Dados de Inspecção (TUXEL):")
df_inspecao = pd.DataFrame(dados_inspecao)
print(df_inspecao)

print("\nDados de Teste (CTA):")
df_teste = pd.DataFrame(dados_teste)
print(df_teste)

colunas_vars = ['Total_Problemas', 'Tempo_min', 'Eficacia_pct', 'Eficiencia_pct']

desc_inspecao = df_inspecao[colunas_vars].agg(['mean', 'std']).T
desc_inspecao.columns = ['Média', 'Desvio Padrão']

